const PROBE_EXCEPTION_ID = makeShortId('MainWindow', 'Probe the connection', '');

/**
 * Add one message for one language file.
 * @param {import('../lib/model.js').TsDocument} document
 * @param {object} entry
 * @param {'en'|'ru'|'zh'} language
 */
function addMessage(document, entry, language) {
  let context = document.contexts.find((candidate) => candidate.name === entry.context);
  if (context === undefined) {
    context = { name: entry.context, messages: [] };
    document.contexts.push(context);
  }
  const fields = {
    source: entry.source,
    comment: entry.comment ?? '',
    extraComment: entry.extraComment ?? '',
    locations: [{ filename: `../src/${entry.file}`, line: String(entry.line) }],
  };

  if (entry.numerus) {
    fields.numerus = true;
    if (language === 'en') {
      fields.numerusForms = [];
      fields.translationType = 'unfinished';
    } else {
      const forms = entry[language];
      fields.numerusForms = Array.isArray(forms) ? [...forms] : [];
      fields.translationType = fields.numerusForms.some((form) => form.length > 0) ? null : 'unfinished';
    }
    context.messages.push(createMessage(entry.context, fields));
    return;
  }

  if (language === 'en') {
    const override = entry.en;
    fields.translation = override ?? '';
    fields.translationType = override === undefined ? 'unfinished' : null;
  } else {
    const value = entry[language];
    if (value !== null && typeof value === 'object') {
      fields.translation = value.translation;
      fields.translationType = value.state ?? 'unfinished';
      fields.translatorComment = value.note ?? '';
    } else if (typeof value === 'string') {
      fields.translation = value;
      fields.translationType = null;
    } else {
      fields.translation = '';
      fields.translationType = 'unfinished';
    }
  }
  context.messages.push(createMessage(entry.context, fields));
}

/**
 * @param {string} language
 * @param {'en'|'ru'|'zh'} variant
 * @returns {import('../lib/model.js').TsDocument}
 */
function buildExample(language, variant) {
  const document = createDocument({ version: '2.1', language, sourceLanguage: 'en' });
  for (const entry of MESSAGES) addMessage(document, entry, variant);
  if (variant === 'ru') {
    const context = { name: 'LegacyDialog', messages: [] };
    context.messages.push(
      createMessage('LegacyDialog', {
        source: 'Legacy option',
        translation: 'Устаревшая опция',
        translationType: 'vanished',
        locations: [{ filename: '../src/legacydialog.cpp', line: '3' }],
      }),
    );
    document.contexts.push(context);
  }
  return document;
}

/**
 * Build a fixture that exercises every construct the writer reproduces.
 * @returns {import('../lib/model.js').TsDocument}
 */
function buildEdge() {
  const document = createDocument({
    version: '2.1',
    language: 'de_DE',
    sourceLanguage: 'en',
    newline: '\r\n',
    dependencies: ['qtbase_de.qm'],
    extras: [['poedit', '1']],
  });
  document.contexts.push({
    name: 'Edge',
    messages: [
      createMessage('Edge', {
        source: '"Quoted" & <tag> \'single\'',
        translation: '„Zitat“ & <tag> \'einfach\'',
        extraComment: 'Exercises entity escaping',
        locations: [{ filename: '../src/mainwindow.cpp', line: '5' }],
      }),
      createMessage('Edge', {
        source: 'Non-breaking\u00A0space',
        translation: 'geschütztes\u00A0Leerzeichen',
      }),
      createMessage('Edge', {
        source: 'Line\rbreak',
        translation: 'Zeilen\rumbruch',
        oldSource: 'Line break',
        userData: 'raw-user-data',
        extras: [['kind', 'edge']],
      }),
      createMessage('Edge', {
        source: '%n edge(s)',
        numerus: true,
        numerusForms: ['%n Kante', '%n Kanten'],
      }),
      createMessage('Edge', {
        source: 'Gone',
        translation: 'Weg',
        translationType: 'vanished',
        translatorComment: 'removed from the sources',
      }),
    ],
  });
  return document;
}

