async function main() {
  await rm(FIXTURES, { recursive: true, force: true });
  await mkdir(EXAMPLE, { recursive: true });
  await mkdir(EDGE, { recursive: true });
  await mkdir(SOURCES, { recursive: true });

  for (const [name, lines] of Object.entries(SOURCE_FILES)) {
    await writeFile(path.join(SOURCES, name), `${lines.join('\n')}\n`, 'utf8');
  }

  await writeFile(
    path.join(EXAMPLE, 'example_en.ts'),
    serialize(buildExample('en_US', 'en')),
    'utf8',
  );
  await writeFile(
    path.join(EXAMPLE, 'example_ru.ts'),
    serialize(buildExample('ru_RU', 'ru')),
    'utf8',
  );
  await writeFile(
    path.join(EXAMPLE, 'example_zh_CN.ts'),
    serialize(buildExample('zh_CN', 'zh')),
    'utf8',
  );
  await writeFile(path.join(EXAMPLE, 'glossary.json'), `${JSON.stringify(GLOSSARY, null, 2)}\n`, 'utf8');
  await writeFile(
    path.join(EXAMPLE, 'README.md'),
    `# Example Qt translation catalog\n\n` +
      `Synthetic catalogs for testing dsh-linguist-tools. They are not copied from any product.\n\n` +
      `- \`example_en.ts\` — source-language overrides (\`Licence\` → \`License\`); everything else is unfinished.\n` +
      `- \`example_ru.ts\` — one draft with a note (\`Snapshot\`), one untranslated entry (\`Export report\`),\n` +
      `  one vanished message, three plural forms.\n` +
      `- \`example_zh_CN.ts\` — one deliberate blank finished entry (\`Tolerance\`), one glossary \`avoid\` hit.\n` +
      `- \`glossary.json\` — full-parity terminology, including a context-scoped term and an exception.\n\n` +
      `The \`<location>\` paths point at \`../src/\`, so \`qt_ts_show\` code excerpts work.\n\n` +
      `Regenerate with \`node scripts/generate-fixtures.mjs\`.\n`,
    'utf8',
  );

  await writeFile(path.join(EDGE, 'edge_ru.ts'), serialize(buildEdge()), 'utf8');
  await writeFile(path.join(EDGE, 'blocked_ru.ts'), BLOCKED, 'utf8');
  await writeFile(path.join(EDGE, 'conflict_ru.ts'), CONFLICT, 'utf8');
  await writeFile(path.join(EDGE, 'drift_ru.ts'), DRIFT, 'utf8');

  console.log(`fixtures written to ${path.relative(ROOT, FIXTURES)}`);
}

await main();
